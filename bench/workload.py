#!/usr/bin/env python3
"""Record how much guest work each kernel of the embedded image does.

    python3 workload.py write RESULT.json [TABLE]
    python3 workload.py compare TABLE RESULT.json [--tolerance PCT]

`write` turns a saved `iris-bench run --deterministic` result into
prebuilt/workload.txt: guest instructions per iteration of every kernel.
`make workload` runs it, and `make prebuilt` runs that after refreshing the
image, so the table is a generated file checked in beside the image, like
golden/golden.h, and CI regenerates it and fails on a diff.

Why: the suite reports rates of compiled guest code, so the image is part of
the workload. 6adc7927 rebuilt it with a different compiler, and Dhrystone
went from 313 to 428 guest instructions per iteration with the emulator
unchanged. A changed image is a binary diff that says nothing about what
changed. This table turns it into a text diff that names the kernels whose
work moved and by how much, and stays unchanged when the code does not
(a comment edit changes the image's debug information but not this file).

The run must come from the plain interpreter (no `lightning`, no `jitv2`)
built with `ci_clock`, in deterministic mode, on the default R4400 with the
full cache model. In a `ci_clock` build the suite's clock counts retired
instructions, so the iteration counts and therefore the table are the same on
every host. `lightning` counts a fused instruction pair once and reads up to
15% low on some kernels, and jitv2 counts differently again, so neither is a
reference.

`compare` checks any saved result against the table with a tolerance, for
reading a timed run. Without `ci_clock` the suite picks iteration counts by
time, and a few kernels (fpu/transcend, fpu/matmul) do work that depends on
the count: about 1% between runs on the same image.
"""

import argparse
import json
import sys

HEADER = """\
# Guest instructions per iteration of each kernel in irisbench.elf.
# Generated by bench/workload.py from a deterministic run of the plain
# interpreter; `make -C bench prebuilt` rewrites it. Do not edit.
#
# A change here means the benchmark measures different work, so results
# from before and after it are not comparable. Say so in the commit.
#
# kernel                      instructions/iteration
"""


def load_result(path):
    with open(path) as f:
        return json.load(f)


def refuse_unless_reference(run, path):
    """Only the run this table is defined by may write it."""
    feats = set(run.get("features", []))
    s = run.get("settings", {})
    why = []
    if "ci_clock" not in feats:
        why.append("not a ci_clock build, so its iteration counts depend on host speed")
    for f in ("lightning", "jitv2"):
        if f in feats:
            why.append(f"a {f} build; the reference is the plain interpreter")
    if not run.get("cell", "").endswith("+deterministic"):
        why.append("not a --deterministic run")
    if s.get("time_pct") != 100:
        why.append(f"not a full run (settings {s})")
    if run.get("machine", {}).get("cpu") != "R4400":
        why.append(f"CPU {run.get('machine', {}).get('cpu')}, not the default R4400")
    if why:
        sys.exit(f"workload.py: {path} cannot define the table: " + "; ".join(why))


def per_iteration(run):
    rows = {}
    for r in run["rows"]:
        if not r.get("iters") or not r.get("icount"):
            sys.exit(f"workload.py: {r['name']} has no instruction count; "
                     "was the test device's timebase missing?")
        rows[r["name"]] = r["icount"] / r["iters"]
    return rows


def format_table(rows):
    return HEADER + "".join(f"{k:<28s}{v:>18.2f}\n" for k, v in rows.items())


def read_table(path):
    rows = {}
    with open(path) as f:
        for line in f:
            if line.strip() and not line.startswith("#"):
                name, value = line.split()
                rows[name] = float(value)
    return rows


def cmd_write(a):
    run = load_result(a.result)
    refuse_unless_reference(run, a.result)
    text = format_table(per_iteration(run))
    if a.table == "-":
        sys.stdout.write(text)
    else:
        with open(a.table, "w") as f:
            f.write(text)
    return 0


def cmd_compare(a):
    want = read_table(a.table)
    got = per_iteration(load_result(a.result))
    bad = 0
    for name in sorted(set(want) | set(got)):
        if name not in got or name not in want:
            print(f"{name}: in {'the table' if name in want else 'the run'} only")
            bad += 1
            continue
        d = (got[name] / want[name] - 1) * 100
        if abs(d) > a.tolerance:
            print(f"{name}: {want[name]:.2f} -> {got[name]:.2f} instructions/iteration ({d:+.2f}%)")
            bad += 1
    print(f"{'ok' if not bad else 'FAIL'}: {bad} of {len(want)} kernels differ by more "
          f"than {a.tolerance}% from {a.table}")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write", help="write the table from a reference run")
    w.add_argument("result")
    w.add_argument("table", nargs="?", default="prebuilt/workload.txt",
                   help="output path, or - for stdout")
    w.set_defaults(fn=cmd_write)
    c = sub.add_parser("compare", help="compare a saved run with the table")
    c.add_argument("table")
    c.add_argument("result")
    c.add_argument("--tolerance", type=float, default=0.5, metavar="PCT")
    c.set_defaults(fn=cmd_compare)
    a = ap.parse_args()
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
