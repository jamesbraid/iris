#!/bin/bash
# Graphics acceptance: boot an installed IRIX disk with the graphics console,
# log in at its shell and run bench/irix/gfx/steps.toml, with MACHINE.toml
# added, through
# `iris-bench irix --strict`. README.md beside this file says what the disks
# need and where the software comes from.
#
# Usage: bench/irix/gfx/run.sh MACHINE OUT-DIR [iris-bench irix options...]
#   MACHINE   fuel, octane or indy
#   OUT-DIR   result JSON, screenshots, the generated config and logs
#
# Environment:
#   IRIS_BIN    directory holding iris and iris-ci (required)
#   IRIS_BENCH  iris-bench binary (default $IRIS_BIN/iris-bench)
#   GFX_DISK    the IRIX system disk, raw (required)
#   GFX_GAMES   the games disk, raw, fitted as SCSI ID 2 (optional)
#   GFX_PROM    PROM image (required on the Fuel and the Octane)
#   GFX_NVRAM   NVRAM to start from, copied (the Fuel needs a seeded one)
#   GFX_FLASH   Fuel boot flash to start from, copied
#   GFX_BOARD   graphics board, in place of the machine's default
#   GFX_PORT    first of four TCP ports on 127.0.0.1 (default 47100)
#
# Both disks run with a copy-on-write overlay in $TMPDIR (else /tmp), so the
# images are never written; the steps write a few megabytes there.
#
# Exits 0 when every step ran or was skipped, 1 when a step failed, and 0
# with a SKIP line when a required disk or PROM is missing, since a host
# without the user's images has nothing to check.

set -u
here=$(cd "$(dirname "$0")" && pwd)
M=${1:?usage: run.sh MACHINE OUT-DIR [iris-bench options]}
OUT=${2:?usage: run.sh MACHINE OUT-DIR [iris-bench options]}
shift 2

skip() { echo "SKIP gfx/$M: $*"; exit 0; }

STEPS=$here/$M.toml
[ -f "$STEPS" ] || { echo "run.sh: no steps for $M (fuel, octane or indy)" >&2; exit 2; }
BIN=${IRIS_BIN:?set IRIS_BIN to the directory holding iris and iris-ci}
BENCH=${IRIS_BENCH:-$BIN/iris-bench}
for b in "$BIN/iris" "$BIN/iris-ci" "$BENCH"; do
    [ -x "$b" ] || { echo "run.sh: $b is not there" >&2; exit 2; }
done

[ -n "${GFX_DISK:-}" ] || skip "no IRIX disk; set GFX_DISK (bench/irix/gfx/README.md)"
[ -f "$GFX_DISK" ] || skip "IRIX disk $GFX_DISK is not there"
case $M in fuel|octane)
    [ -n "${GFX_PROM:-}" ] || skip "no PROM; set GFX_PROM"
    [ -f "$GFX_PROM" ] || skip "PROM $GFX_PROM is not there" ;;
esac
GAMES=${GFX_GAMES:-}
if [ -n "$GAMES" ] && [ ! -f "$GAMES" ]; then
    echo "run.sh: games disk $GAMES is not there; the game steps will be skipped"
    GAMES=
fi
[ -n "$GAMES" ] || echo "run.sh: no games disk; the game steps will be skipped"

P=${GFX_PORT:-47100}
mkdir -p "$OUT" || exit 2
OUT=$(cd "$OUT" && pwd)
rm -f "$OUT/ci.sock" "$OUT/nvram.bin" "$OUT/flash.bin"
if [ -n "${GFX_NVRAM:-}" ]; then
    cp "$GFX_NVRAM" "$OUT/nvram.bin" || exit 2
    [ -f "$GFX_NVRAM.clock" ] && cp "$GFX_NVRAM.clock" "$OUT/nvram.bin.clock"
fi
[ -n "${GFX_FLASH:-}" ] && { cp "$GFX_FLASH" "$OUT/flash.bin" || exit 2; }

CFG=$OUT/machine.toml
{
    echo "# Generated by bench/irix/gfx/run.sh $M."
    [ -n "${GFX_PROM:-}" ] && echo "prom = \"$GFX_PROM\""
    echo "nvram = \"$OUT/nvram.bin\""
    echo "monitor_port = $P"
    echo "serial_port_a = $((P + 1))"
    echo "serial_port_b = $((P + 2))"
    echo "serial_log = \"$OUT/serial.log\""
    echo "no_audio = true"
    echo "ci = true"
    echo "ci_socket = \"$OUT/ci.sock\""
    case $M in
    fuel)
        echo 'banks = [256, 256]'
        printf '[machine]\nprofile = "fuel_ip34"\ncpu = "r14000"\n'
        printf '[graphics]\nboard = "%s"\n' "${GFX_BOARD:-v12}"
        printf '[fuel]\nconsole = "l1"\nl1_port = %d\nflash = "%s"\n' $((P + 3)) "$OUT/flash.bin" ;;
    octane)
        echo 'banks = [256]'
        printf '[machine]\nprofile = "octane_ip30"\ncpu = "r10000"\n'
        [ -n "${GFX_BOARD:-}" ] && printf '[graphics]\nboard = "%s"\n' "$GFX_BOARD"
        [ -f "$OUT/flash.bin" ] && printf '[octane]\nflash = "%s"\n' "$OUT/flash.bin" ;;
    indy)
        echo 'banks = [128, 128, 0, 0]'
        printf '[machine]\nprofile = "indy_ip24"\ncpu = "r4400"\n'
        [ -n "${GFX_BOARD:-}" ] && printf '[graphics]\nboard = "%s"\n' "$GFX_BOARD" ;;
    esac
    printf '[scsi.1]\npath = "%s"\noverlay = true\n' "$GFX_DISK"
    [ -n "$GAMES" ] && printf '[scsi.2]\npath = "%s"\noverlay = true\n' "$GAMES"
} > "$CFG"
# The Indy's PROM starts from an empty NVRAM file and finds the disk itself.
[ -f "$OUT/nvram.bin" ] || : > "$OUT/nvram.bin"

ci() { "$BIN/iris-ci" --socket "$OUT/ci.sock" "$@"; }

"$BIN/iris" --config "$CFG" > "$OUT/iris.stderr" 2>&1 &
pid=$!
stop() {
    ci quit > /dev/null 2>&1
    for _ in $(seq 30); do kill -0 $pid 2>/dev/null || break; sleep 1; done
    kill $pid 2>/dev/null
    wait $pid 2>/dev/null
}
trap stop EXIT

ci status --wait-ready 120 > /dev/null || { echo "run.sh: iris did not come up"; tail "$OUT/iris.stderr"; exit 1; }
ci start > /dev/null
t0=$(date +%s)
if ! ci serial-wait "login:" --timeout 1800 > "$OUT/boot.out" 2>&1; then
    echo "FAIL gfx/$M: no login prompt on the console in 1800 s"
    exit 1
fi
echo "run.sh: login prompt after $(( $(date +%s) - t0 )) s"
ci login > "$OUT/login.out" 2>&1 || { echo "FAIL gfx/$M: could not log in on the console"; exit 1; }

"$BENCH" irix --ci "$BIN/iris-ci" --socket "$OUT/ci.sock" --monitor "127.0.0.1:$P" \
    --steps "$here/steps.toml" --extra-steps "$STEPS" --label "gfx-$M" --out "$OUT" --shots "$OUT" --strict "$@"
rc=$?
[ $rc -eq 0 ] && echo "PASS gfx/$M" || echo "FAIL gfx/$M"
exit $rc
